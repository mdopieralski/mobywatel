// Builds src/cities-data.ts: every Polish town (miasto) with its voivodeship and population.
// Source: Wikidata (CC0), towns with a TERYT SIMC id, not dissolved, in one of the 16 current voivodeships.
// Run: pnpm --filter @mobywatel/content run build:cities
// The app ships the result, so the city search works offline and sends nothing anywhere.
import { writeFile } from 'node:fs/promises';

const VOIVODESHIPS = [
  'dolnośląskie',
  'kujawsko-pomorskie',
  'lubelskie',
  'lubuskie',
  'łódzkie',
  'małopolskie',
  'mazowieckie',
  'opolskie',
  'podkarpackie',
  'podlaskie',
  'pomorskie',
  'śląskie',
  'świętokrzyskie',
  'warmińsko-mazurskie',
  'wielkopolskie',
  'zachodniopomorskie',
];

const QUERY = `SELECT ?c ?name ?vname (MAX(?pop) AS ?population) WHERE {
  ?c wdt:P31/wdt:P279* wd:Q515; wdt:P17 wd:Q36; wdt:P4046 ?simc.
  FILTER NOT EXISTS { ?c wdt:P576 ?end }
  ?c rdfs:label ?name FILTER(lang(?name) = "pl")
  OPTIONAL { ?c wdt:P1082 ?pop }
  OPTIONAL { ?c wdt:P131+ ?v. ?v wdt:P31 wd:Q150093. ?v rdfs:label ?vname FILTER(lang(?vname) = "pl") }
} GROUP BY ?c ?name ?vname`;

const url = `https://query.wikidata.org/sparql?query=${encodeURIComponent(QUERY)}`;
const response = await fetch(url, {
  headers: {
    Accept: 'application/sparql-results+json',
    'User-Agent': 'sprawnie-prototype/0.1 (city list build, https://mobywatel.ai entry)',
  },
});
if (!response.ok) {
  throw new Error(`Wikidata answered ${response.status}`);
}
const rows = (await response.json()).results.bindings;

// One entry per town; old (pre-1999) voivodeships are dropped.
const towns = new Map();
for (const row of rows) {
  const voivodeship = VOIVODESHIPS.indexOf((row.vname?.value ?? '').replace(/^województwo /, ''));
  if (voivodeship === -1) {
    continue;
  }
  const population = row.population ? Math.round(Number(row.population.value)) : 0;
  towns.set(row.c.value, [row.name.value, voivodeship, population]);
}

const collator = new Intl.Collator('pl');
const list = [...towns.values()].sort((a, b) => collator.compare(a[0], b[0]) || a[1] - b[1]);
if (list.length < 900) {
  throw new Error(`Only ${list.length} towns: the query or Wikidata changed, keep the old file`);
}

const out = `// Generated by scripts/build-cities.mjs from Wikidata (CC0) on ${new Date().toISOString().slice(0, 10)}.
// Do not edit by hand: run \`pnpm --filter @mobywatel/content run build:cities\`.
// [name, voivodeship index, population (0 = unknown)]

export const VOIVODESHIPS = ${JSON.stringify(VOIVODESHIPS)} as const;

export const CITY_ROWS: readonly (readonly [string, number, number])[] = ${JSON.stringify(list)};
`;
await writeFile(new URL('../src/cities-data.ts', import.meta.url), out);
console.log(`${list.length} towns written`);
